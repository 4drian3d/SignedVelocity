plugins {
    alias(libs.plugins.runvelocity)
    alias(libs.plugins.idea.ext)
    alias(libs.plugins.blossom)
    alias(libs.plugins.shadow)
}

dependencies {
    compileOnly(libs.velocity.api)
    annotationProcessor(libs.velocity.api)
    implementation(libs.bstats)

    compileOnly(libs.packetevents.velocity)
    implementation(projects.signedvelocityShared)
}

tasks {
    // Velocity 4.x artifacts are published for JVM 25 — this module must match,
    // overriding the repo-wide release 21 set in the root build script.
    withType<JavaCompile> {
        options.release.set(25)
    }
    build {
        dependsOn(shadowJar)
    }
    clean {
        // Deletes the directory that is generated by the runVelocity plugin
        delete("run")
    }
    runVelocity {
        velocityVersion(libs.versions.velocity.get())
        downloadPlugins {
            modrinth("vpacketevents", "Kz7ttviZ")
        }
    }
    shadowJar {
        archiveBaseName.set("${rootProject.name}-Proxy")
        archiveClassifier.set("")
        relocate("org.bstats", "io.github._4drian3d.signedvelocity.libs.bstats")
        minimize()
        doLast {
            copy {
                from(archiveFile)
                into("${rootProject.projectDir}/build")
            }
        }
    }
}

sourceSets {
    main {
        blossom {
            javaSources {
                property("version", project.version.toString())
            }
        }
    }
}
